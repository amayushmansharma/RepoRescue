import type { Finding, PullRequestDraft, RemediationProposal, RepositorySnapshot } from "@/lib/types";
import { SEVERITY_RANK } from "./remediations";

const BOUNDARY_NOTE =
  "Preview only. RepoRescue prepared this metadata locally: no branch, commit, push or pull request was created, and no GitHub write of any kind occurred.";

function shortHash(value: string): string {
  let hash = 5381;
  for (let index = 0; index < value.length; index += 1) {
    hash = ((hash << 5) + hash + value.charCodeAt(index)) % 0xffffffff;
  }
  return Math.abs(hash).toString(16).padStart(8, "0").slice(0, 8);
}

export function buildPullRequestDraft(input: {
  snapshot: RepositorySnapshot;
  findings: Finding[];
  proposals: RemediationProposal[];
  beforeScore: number;
  automatedCheck?: { passed: number; failed: number; skipped: number } | null;
  verificationSummary?: string | null;
}): PullRequestDraft {
  const { snapshot, findings, proposals } = input;
  const selectedIds = new Set(proposals.map((proposal) => proposal.findingId));
  const selected = findings
    .filter((finding) => selectedIds.has(finding.id))
    .sort((a, b) => SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] || a.ruleId.localeCompare(b.ruleId));
  const patchProposals = proposals.filter((proposal) => proposal.kind === "patch");
  const manualProposals = proposals.filter((proposal) => proposal.kind === "manual");
  const touchedFiles = Array.from(
    new Map(patchProposals.flatMap((proposal) => proposal.files.map((file) => [file.path, file]))).values(),
  ).sort((a, b) => a.path.localeCompare(b.path));
  const manualFindings = findings.filter((finding) => finding.remediation.kind === "manual");

  const validationLines = patchProposals.flatMap((proposal) =>
    proposal.validation
      .filter((check) => check.id !== "patch-consistency")
      .map((check) => `- \`${proposal.findingId}\`: ${check.label} — ${check.state}${check.state === "passed" ? "" : ` (${check.detail})`}`),
  );

  const description = `## Problem

RepoRescue's readiness scan of \`${snapshot.repository.fullName}\` (score **${input.beforeScore}/100**) produced ${findings.length} evidence-backed onboarding finding${findings.length === 1 ? "" : "s"}. This change addresses ${patchProposals.length} of them:

${selected
  .map((finding) => `- **${finding.severity.toUpperCase()}** \`${finding.ruleId}\` — ${finding.title}`)
  .join("\n") || "- (no findings selected)"}

## Proposed changes

| Finding | Intended outcome | Files |
| --- | --- | --- |
${patchProposals
  .map(
    (proposal) =>
      `| \`${proposal.findingId}\` | ${proposal.outcome.replace(/\|/g, "\\|")} | ${proposal.files.map((file) => `\`${file.path}\``).join(", ")} |`,
  )
  .join("\n") || "| — | No file changes were generated | — |"}

## Why this is useful

A new contributor currently has to guess how to install, configure and validate this project. These changes document the evidence-backed gaps (required environment keys, runtime requirements, CI, contribution guidance and repository scaffolding) so the first contribution does not depend on maintainer archaeology.

## Validation performed

${validationLines.length > 0 ? validationLines.join("\n") : "- No automated validation was applicable to the selected changes."}
${input.automatedCheck ? `- Local re-analysis: ${input.automatedCheck.passed} resolved, ${input.automatedCheck.failed} still detected, ${input.automatedCheck.skipped} manual.` : "- Before/after re-analysis: not run yet. Use RepoRescue Verify to record it."}

RepoRescue did **not** install dependencies or execute repository code, so none of the above is a test-suite result.

## Remaining limitations

${manualProposals.length > 0 ? manualProposals.map((proposal) => `- \`${proposal.findingId}\` still needs manual work: ${proposal.outcome}`).join("\n") : "- No manual follow-ups were selected."}
- ${manualFindings.length} finding${manualFindings.length === 1 ? "" : "s"} in the scan require a maintainer decision and are not addressed by this patch.
- Generated text and runtime versions are proposals; a maintainer must review every line.
- CI has not run for this change, and no pull request has been opened.
${input.verificationSummary ? `\n### Recorded verification\n\n${input.verificationSummary}` : ""}

---
Generated by RepoRescue from repository evidence. Preview metadata only: nothing was committed or pushed.`;

  return {
    title: patchProposals.length > 0 ? `docs: improve contributor onboarding (${patchProposals.length} readiness fixes)` : "docs: contributor onboarding improvements",
    branch: `reborescue/readiness-${shortHash(selected.map((finding) => finding.id).sort().join(",") || "none")}`,
    baseBranch: snapshot.repository.defaultBranch || "main",
    description,
    files: touchedFiles.map((file) => ({
      path: file.path,
      changeType: file.changeType,
      additions: file.additions,
      deletions: file.deletions,
    })),
    checklist: [
      {
        label: "Every selected automated finding has a reviewable patch",
        done: patchProposals.length > 0,
        note: `${patchProposals.length} patch proposal(s)`,
      },
      {
        label: "Generated files passed the available syntax validators",
        done: patchProposals.length > 0 && patchProposals.every((proposal) => proposal.overallValidation === "passed"),
        note: patchProposals.some((proposal) => proposal.overallValidation !== "passed") ? "Some validators failed or were skipped" : undefined,
      },
      {
        label: "A human reviewed every diff line",
        done: false,
        note: "Required before opening a pull request",
      },
      {
        label: "Verification recorded (before/after re-analysis)",
        done: Boolean(input.verificationSummary),
        note: input.verificationSummary ? "Recorded in this session" : "Run Verify before submitting",
      },
      {
        label: "Manual findings handed to a maintainer",
        done: false,
        note: `${manualFindings.length} finding(s) require human decisions`,
      },
      {
        label: "Branch, commit and pull request created",
        done: false,
        note: "Not performed: GitHub writes are disabled in this build",
      },
    ],
    boundaryNote: BOUNDARY_NOTE,
  };
}
