/** Rule ids that have an implemented, rule-based automatic remediation. */
export const AUTOMATED_REMEDIATION_RULE_IDS = Object.keys(BUILDERS).sort();
export function buildRemediationPlan(snapshot, findings, selectedIds, now) {
    const ctx = buildRuleContext(snapshot);
    const working = new Map(snapshot.files.map((file) => [file.path, file.content]));
    const selected = new Set(selectedIds);
    const ordered = findings
        .filter((finding) => selected.has(finding.id))
        .sort((a, b) => SEVERITY_RANK[a.severity] - SEVERITY_RANK[b.severity] || a.ruleId.localeCompare(b.ruleId));
    const proposals = [];
    const unresolved = [];
    const touched = new Set();
    for (const finding of ordered) {
        if (!isSafeFinding(finding))
            continue;
        const builder = finding.remediation.kind === "auto" ? BUILDERS[finding.ruleId] : undefined;
        if (!builder) {
            proposals.push(manualProposal(finding, now, finding.remediation.kind === "auto" ? "RepoRescue has no safe automatic remediation for this finding." : undefined));
            continue;
        }
        const result = builder(ctx, working);
        if (!result.ok) {
            unresolved.push({ findingId: finding.id, reason: result.reason });
            proposals.push(manualProposal(finding, now, result.reason));
            continue;
        }
        const safeChanges = result.changes.filter((change) => isSafeRepositoryPath(change.path));
        if (safeChanges.length === 0) {
            unresolved.push({ findingId: finding.id, reason: "Generated patch paths failed safety validation." });
            proposals.push(manualProposal(finding, now, "Generated patch paths failed safety validation."));
            continue;
        }
        const files = safeChanges.map((change) => {
            const original = working.has(change.path) ? working.get(change.path) : null;
            const diff = unifiedDiff(change.path, original, change.content);
            return {
                path: change.path,
                changeType: original === null ? "create" : "modify",
                original,
                proposed: change.content,
                diff: diff.diff,
                additions: diff.additions,
                deletions: diff.deletions,
            };
        });
        const validation = [];
        const consistency = files.length > 0 && files.every((file) => isSafeRepositoryPath(file.path) && file.diff.length > 0);
        validation.push({
            id: "patch-consistency",
            label: "Patch consistency",
            state: consistency ? "passed" : "failed",
            detail: consistency
                ? `${files.length} file change(s) generated; diffs contain ${files.reduce((total, file) => total + file.additions, 0)} addition(s) and ${files.reduce((total, file) => total + file.deletions, 0)} deletion(s).`
                : "One or more generated file changes are empty or have an unsafe path.",
        });
        for (const file of files) {
            validation.push(...validateFileContent(file.path, file.proposed));
            working.set(file.path, file.proposed);
            touched.add(file.path);
        }
        proposals.push({
            id: `rr-${finding.id}`,
            findingId: finding.id,
            findingTitle: finding.title,
            kind: "patch",
            outcome: result.outcome,
            files,
            validation,
            overallValidation: summariseValidation(validation),
            limitations: ["No change was applied to the repository; this is a proposed patch generated from documented rules.", ...result.limitations],
            assumptions: result.assumptions,
            instructions: result.instructions,
            generatedAt: now,
        });
    }
    return {
        proposals,
        patchedFiles: Array.from(touched).map((path) => ({ path, content: working.get(path) })),
        unresolved,
    };
}
function isSafeFinding(finding) {
    return typeof finding.id === "string" && finding.id.length > 0 && finding.id.length < 120;
}
function manualProposal(finding, now, reasonOverride) {
    return {
        id: `rr-${finding.id}`,
        findingId: finding.id,
        findingTitle: finding.title,
        kind: "manual",
        outcome: finding.recommendation,
        files: [],
        validation: [],
        overallValidation: "skipped",
        limitations: [
            reasonOverride ?? "This finding requires a human decision, so RepoRescue does not generate a file patch.",
            "No automatic change was generated or validated.",
        ],
        assumptions: [],
        instructions: finding.remediation.steps ?? [finding.recommendation],
        generatedAt: now,
    };
}
export function applyPlanToSnapshot(snapshot, plan) {
    if (plan.patchedFiles.length === 0)
        return snapshot;
    const files = snapshot.files.map((file) => {
        const patched = plan.patchedFiles.find((entry) => entry.path === file.path);
        if (!patched)
            return file;
        return { ...file, content: patched.content, bytes: Buffer.byteLength(patched.content, "utf8"), truncated: false };
    });
    for (const patched of plan.patchedFiles) {
        if (!files.some((file) => file.path === patched.path)) {
            files.push({ path: patched.path, content: patched.content, bytes: Buffer.byteLength(patched.content, "utf8"), truncated: false });
        }
    }
    const tree = Array.from(new Set([...snapshot.tree, ...plan.patchedFiles.map((entry) => entry.path)])).sort();
    return buildSnapshot({
        repository: snapshot.repository,
        files: files.map((file) => ({ path: file.path, content: file.content })),
        tree,
        mode: snapshot.mode,
        fetchedAt: snapshot.fetchedAt,
        analysisLimitations: [
            ...snapshot.analysisLimitations,
            `Verification applied ${plan.patchedFiles.length} proposed file change(s) in an in-memory workspace; the repository itself was not modified.`,
        ],
    });
}
export function readmeHeadingsFor(snapshot) {
    const readme = findFile(snapshot, /^readme(\.(md|markdown|rst|txt))?$/i);
    if (!readme)
        return [];
    return markdownHeadings(readme.content).map((heading) => heading.text);
}
