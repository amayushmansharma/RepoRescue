function ensureTrailingNewline(content) {
    return content.endsWith("\n") ? content : `${content}\n`;
}
function insertSection(content, title, body) {
    const lines = content.replace(/\r\n/g, "\n").split("\n");
    const trailing = findHeading(content, [/^license(s|d)?\b/i, /^support\b/i, /^acknowledg/i, /^credits\b/i]);
    const section = [`## ${title}`, "", body.trim(), ""];
    if (trailing) {
        const index = trailing.line - 1;
        const before = lines.slice(0, index);
        while (before.length > 0 && before[before.length - 1].trim() === "")
            before.pop();
        const after = lines.slice(index);
        return ensureTrailingNewline([...before, "", ...section, ...after].join("\n"));
    }
    const base = lines.slice();
    while (base.length > 0 && base[base.length - 1].trim() === "")
        base.pop();
    return ensureTrailingNewline([...base, "", ...section].join("\n"));
}
function envPlaceholder(key) {
    if (/(SECRET|TOKEN|PASSWORD|PASS|CREDENTIAL|PRIVATE)/.test(key))
        return "replace-with-a-local-secret";
    if (/(DATABASE_URL|DB_URL|DSN)/.test(key))
        return "postgresql://user:password@localhost:5432/app";
    if (/(URL|URI)/.test(key))
        return "http://localhost:3000";
    if (/PORT/.test(key))
        return "3000";
    if (/(ENV|MODE)/.test(key))
        return "development";
    if (/(HOST)/.test(key))
        return "localhost";
    return "";
}
function envTemplateBody(ctx, keys) {
    const lines = [
        "# Copy this file to .env and fill in local values.",
        "# Placeholder values only: never commit real credentials.",
        "",
    ];
    for (const entry of keys) {
        lines.push(`# used in ${entry.path}:${entry.line}`);
        lines.push(`${entry.key}=${envPlaceholder(entry.key)}`);
        lines.push("");
    }
    return lines.join("\n");
}
function requirementsBody(ctx, working) {
    const assumptions = [];
    const ecosystem = ctx.snapshot.ecosystem.id;
    const lines = [];
    let enginesChange;
    if (ecosystem === "node") {
        const pkgRaw = working.get("package.json");
        let engines;
        let pkg = null;
        if (pkgRaw) {
            try {
                pkg = JSON.parse(pkgRaw);
                const declared = pkg.engines;
                if (declared && typeof declared.node === "string")
                    engines = declared.node;
            }
            catch {
                pkg = null;
            }
        }
        if (!engines) {
            engines = ">=20";
            assumptions.push("Node.js 20 is proposed because package.json declares no engines field. Confirm the supported Node version with the maintainers before submitting.");
            if (pkg) {
                const updated = { ...pkg, engines: { ...pkg.engines, node: engines } };
                enginesChange = {
                    path: "package.json",
                    changeType: "modify",
                    content: `${JSON.stringify(updated, null, 2)}\n`,
                };
            }
        }
        lines.push(`- Node.js \`${engines}\``);
        lines.push(`- ${ctx.packageManager.command}${ctx.packageManager.lockfile ? ` (lockfile: ${ctx.packageManager.lockfile})` : " (no lockfile committed yet)"}`);
    }
    else if (ecosystem === "python") {
        const pyproject = working.get("pyproject.toml") ?? "";
        const requires = /python\s*=\s*["']([^"']+)["']/.exec(pyproject)?.[1];
        lines.push(`- Python ${requires ? requires.replace(/[\^~]/g, "") + " or newer" : "3.11 or newer"}${requires ? " (declared in pyproject.toml)" : ""}`);
        if (ctx.snapshot.tree.includes("poetry.lock"))
            lines.push("- Poetry (lockfile committed)");
    }
    else if (ecosystem === "java") {
        const pom = working.get("pom.xml") ?? "";
        const version = /<java\.version>([^<]+)</.exec(pom)?.[1];
        if (version)
            lines.push(`- JDK ${version}`);
        else {
            lines.push("- JDK 17 or newer");
            assumptions.push("JDK 17 is proposed because no Java version is declared. Confirm the required JDK before submitting.");
        }
        lines.push(ctx.snapshot.tree.includes("pom.xml") ? "- Maven" : "- Gradle");
    }
    else if (ecosystem === "go") {
        const goVersion = /^go\s+([\d.]+)$/m.exec(working.get("go.mod") ?? "")?.[1];
        lines.push(`- Go ${goVersion ?? "1.22 or newer"}${goVersion ? " (declared in go.mod)" : ""}`);
    }
    else if (ecosystem === "rust") {
        lines.push("- A stable Rust toolchain (install with rustup)");
    }
    else {
        lines.push("- Document the runtime and services this project requires.");
        assumptions.push("The ecosystem could not be detected, so the requirement list is a placeholder.");
    }
    if (ctx.envKeys.length > 0) {
        lines.push("- A local `.env` created from `.env.example`");
    }
    return { body: lines.join("\n"), assumptions, enginesChange };
}
function ciWorkflow(ctx) {
    const ecosystem = ctx.snapshot.ecosystem.id;
    const limitations = [];
    const assumptions = [];
    const header = [
        "# Generated by RepoRescue from repository evidence. Review before committing.",
        "name: ci",
        "",
        "on:",
        "  push:",
        "    branches: [main]",
        "  pull_request:",
        "",
        "permissions:",
        "  contents: read",
        "",
        "jobs:",
    ];
    if (ecosystem === "node") {
        const pkgRaw = ctx.snapshot.files.find((file) => file.path === "package.json")?.content ?? "{}";
        let scripts = {};
        try {
            scripts = (JSON.parse(pkgRaw).scripts ?? {});
        }
        catch {
            scripts = {};
        }
        const pm = ctx.packageManager.command;
        const hasLock = !!ctx.packageManager.lockfile;
        const install = hasLock ? (pm === "npm" ? "npm ci" : `${pm} install --frozen-lockfile`) : `${pm} install`;
        if (!hasLock)
            limitations.push("No lockfile is committed, so the workflow falls back to an unlocked install.");
        const steps = [
            "    runs-on: ubuntu-latest",
            "    steps:",
            "      - uses: actions/checkout@v4",
            "      - uses: actions/setup-node@v4",
            "        with:",
            '          node-version: "20"',
            ...(pm === "npm" && hasLock ? ["          cache: npm"] : []),
            "      - name: Install dependencies",
            `        run: ${install}`,
        ];
        if (scripts.typecheck)
            steps.push("      - name: Typecheck", `        run: ${pm} run typecheck`);
        if (scripts.lint)
            steps.push("      - name: Lint", `        run: ${pm} run lint`);
        if (scripts.build)
            steps.push("      - name: Build", `        run: ${pm} run build`);
        if (scripts.test && !/no test specified/i.test(scripts.test))
            steps.push("      - name: Tests", `        run: ${pm} test`);
        else {
            steps.push("      # TODO: add a test step once this repository has a test suite.");
            limitations.push("The workflow deliberately does not run tests because this repository has no test command yet.");
        }
        return { content: [...header, "  verify:", ...steps, ""].join("\n"), limitations, assumptions };
    }
    if (ecosystem === "python") {
        const steps = [
            "    runs-on: ubuntu-latest",
            "    steps:",
            "      - uses: actions/checkout@v4",
            "      - uses: actions/setup-python@v5",
            "        with:",
            '          python-version: "3.11"',
            "      - name: Install",
            "        run: |",
            "          python -m pip install --upgrade pip",
            ctx.snapshot.tree.includes("poetry.lock")
                ? "          pip install poetry && poetry install"
                : "          pip install -r requirements.txt",
        ];
        if (ctx.testCommand)
            steps.push("      - name: Tests", `        run: ${ctx.testCommand}`);
        else {
            steps.push("      # TODO: add a test command once one exists.");
            limitations.push("The workflow does not run tests because no test command was detected.");
        }
        assumptions.push("Python 3.11 is proposed for the CI matrix; adjust it to the versions you support.");
        return { content: [...header, "  test:", ...steps, ""].join("\n"), limitations, assumptions };
    }
    const generic = {
        go: ["    runs-on: ubuntu-latest", "    steps:", "      - uses: actions/checkout@v4", "      - uses: actions/setup-go@v5", "        with:", '          go-version: "1.22"', "      - run: go build ./...", "      - run: go test ./..."],
        rust: ["    runs-on: ubuntu-latest", "    steps:", "      - uses: actions/checkout@v4", "      - uses: dtolnay/rust-toolchain@stable", "      - run: cargo build --all-targets", "      - run: cargo test --all"],
        java: ["    runs-on: ubuntu-latest", "    steps:", "      - uses: actions/checkout@v4", "      - uses: actions/setup-java@v4", "        with:", '          distribution: temurin', '          java-version: "17"', "      - run: mvn --batch-mode verify"],
    };
    const steps = generic[ecosystem];
    if (!steps) {
        assumptions.push("The ecosystem could not be detected, so a minimal workflow with a TODO was generated.");
        limitations.push("This workflow contains a TODO step and does not build or test anything yet.");
        return {
            content: [
                ...header,
                "  verify:",
                "    runs-on: ubuntu-latest",
                "    steps:",
                "      - uses: actions/checkout@v4",
                "      # TODO: replace with your install, build and test commands.",
                "      - run: echo 'Configure this workflow for your project'",
                "",
            ].join("\n"),
            limitations,
            assumptions,
        };
    }
    assumptions.push("Workflow action versions and the runtime version are proposed defaults; confirm they match your support policy.");
    return { content: [...header, "  verify:", ...steps, ""].join("\n"), limitations, assumptions };
}
